-- The original date rule uses the database clock, which Oracle excludes from CHECK.
CREATE TRIGGER trg_users_created_date
BEFORE INSERT OR UPDATE OF created_date ON Users
FOR EACH ROW
BEGIN
    IF TRUNC(:NEW.created_date) > TRUNC(SYSDATE) THEN
        RAISE_APPLICATION_ERROR(-20003, 'Users.created_date cannot be in the future.');
    END IF;
END;
