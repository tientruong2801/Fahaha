CREATE TABLE Users
(
    user_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY (START WITH 116) PRIMARY KEY,
    username VARCHAR2(50 CHAR) NOT NULL,
    password VARCHAR2(100 CHAR) NOT NULL,
    fname VARCHAR2(50 CHAR) NOT NULL,
    lname VARCHAR2(50 CHAR) NOT NULL,
    email VARCHAR2(100 CHAR) NOT NULL UNIQUE,
    note CLOB,
    created_date DATE
);

CREATE TABLE Staff
(
    user_id NUMBER(10) PRIMARY KEY,
    branch VARCHAR2(100 CHAR),
