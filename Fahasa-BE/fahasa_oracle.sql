DECLARE
    existing_object VARCHAR2(128);
BEGIN
    IF USER IN ('SYS', 'SYSTEM') OR SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA') <> USER THEN
        RAISE_APPLICATION_ERROR(-20001, 'Connect as the application schema owner.');
    END IF;
    SELECT MIN(object_name) INTO existing_object
    FROM user_objects
    WHERE object_type IN ('TABLE', 'VIEW', 'MATERIALIZED VIEW', 'SEQUENCE', 'SYNONYM',
